	// Writes a custom chip and every custom chip it uses as structural Verilog-2001:
	// one module per custom chip, built-in gates as continuous assignments.
	//
	// Logic chips (NAND, tri-state buffer, split/merge, bus) translate exactly. Clock, key
	// and pulse become small simulation-only helper modules, ROMs get their contents, and
	// displays/buzzers have no hardware equivalent and are left out with a comment.
	public static class VerilogExporter
	{
		static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
		{
			"always", "and", "assign", "begin", "buf", "bufif0", "bufif1", "case", "casex", "casez", "cmos", "deassign",
			"default", "defparam", "disable", "edge", "else", "end", "endcase", "endfunction", "endmodule", "endprimitive",
			"endspecify", "endtable", "endtask", "event", "for", "force", "forever", "fork", "function", "generate",
			"genvar", "highz0", "highz1", "if", "ifnone", "initial", "inout", "input", "integer", "join", "large",
			"localparam", "macromodule", "medium", "module", "nand", "negedge", "nmos", "nor", "not", "notif0", "notif1",
			"or", "output", "parameter", "pmos", "posedge", "primitive", "pull0", "pull1", "pulldown", "pullup", "rcmos",
			"real", "realtime", "reg", "release", "repeat", "rnmos", "rpmos", "rtran", "rtranif0", "rtranif1", "scalared",
			"signed", "small", "specify", "specparam", "strong0", "strong1", "supply0", "supply1", "table", "task", "time",
			"tran", "tranif0", "tranif1", "tri", "tri0", "tri1", "triand", "trior", "trireg", "vectored", "wait", "wand",
			"weak0", "weak1", "while", "wire", "wor", "xnor", "xor", "automatic", "cell", "config", "design", "endconfig",
			"endgenerate", "incdir", "include", "instance", "liblist", "library", "noshowcancelled", "pulsestyle_ondetect",
			"pulsestyle_onevent", "showcancelled", "unsigned", "use", "uwire"
		};

		const string ClockModule = "rewired_clock";
		const string KeyModule = "rewired_key";
		const string PulseModule = "rewired_pulse";

		public static string Export(ChipDescription root, ChipLibrary library) => Export(root, library, out _);

		public static string Export(ChipDescription root, ChipLibrary library, out string topModuleName)
		{
			if (root == null) throw new ArgumentNullException(nameof(root));
			if (library == null) throw new ArgumentNullException(nameof(library));
			if (root.ChipType != ChipType.Custom) throw new ArgumentException("Only custom chips can be exported.");

			List<ChipDescription> order = new();
			CollectDependenciesFirst(root, library, order, new HashSet<string>(ChipDescription.NameComparer), new HashSet<string>(ChipDescription.NameComparer));

			Dictionary<string, string> moduleNames = new(ChipDescription.NameComparer);
			HashSet<string> usedModuleNames = new(StringComparer.Ordinal) { ClockModule, KeyModule, PulseModule };
			foreach (ChipDescription chip in order) moduleNames[chip.Name] = Unique(Identifier(chip.Name), usedModuleNames);
			topModuleName = moduleNames[root.Name];

			StringBuilder body = new();
			HashSet<string> helpers = new(StringComparer.Ordinal);
			foreach (ChipDescription chip in order)
			{
				new ModuleWriter(chip, library, moduleNames, helpers, usedModuleNames, body).Write();
			}

			StringBuilder sb = new();
			sb.AppendLine($"// Generated by Rewired from custom chip \"{root.Name}\".");
			sb.AppendLine("// Logic is exported exactly; clock, key and pulse are simulation-only helpers.");
			sb.AppendLine("`timescale 1ns / 1ps");
			sb.AppendLine();
			sb.Append(body);
			if (helpers.Contains(ClockModule)) sb.Append(ClockModuleSource);
			if (helpers.Contains(KeyModule)) sb.Append(KeyModuleSource);
			if (helpers.Contains(PulseModule)) sb.Append(PulseModuleSource);
			return sb.ToString();
		}

		static void CollectDependenciesFirst(ChipDescription chip, ChipLibrary library, List<ChipDescription> order, HashSet<string> done, HashSet<string> active)
		{
			if (done.Contains(chip.Name)) return;
			if (!active.Add(chip.Name)) throw new InvalidOperationException("Recursive chip dependency: " + chip.Name);

			foreach (SubChipDescription sub in chip.SubChips ?? Array.Empty<SubChipDescription>())
			{
				if (!library.TryGetChipDescription(sub.Name, out ChipDescription child)) throw new InvalidOperationException("Missing chip: " + sub.Name);
				if (child.ChipType == ChipType.Custom) CollectDependenciesFirst(child, library, order, done, active);
			}

			active.Remove(chip.Name);
			done.Add(chip.Name);
			order.Add(chip);
		}

		sealed class ModuleWriter
		{
			readonly ChipDescription chip;
			readonly ChipLibrary library;
			readonly Dictionary<string, string> moduleNames;
			readonly HashSet<string> helpers;
			readonly HashSet<string> usedModuleNames;
			readonly StringBuilder output;

			readonly HashSet<string> usedNames = new(StringComparer.Ordinal);
			readonly Dictionary<(int owner, int pin), Net> sources = new();
			readonly Dictionary<(int owner, int pin), Net> targets = new();
			readonly Dictionary<int, ChipDescription> subChipDescriptions = new();
			readonly StringBuilder declarations = new();
			readonly StringBuilder statements = new();

			sealed class Net
			{
				public string Name;
				public int Width;
				public bool IsPort;
				public bool Driven;
			}

			public ModuleWriter(ChipDescription chip, ChipLibrary library, Dictionary<string, string> moduleNames, HashSet<string> helpers, HashSet<string> usedModuleNames, StringBuilder output)
			{
				this.chip = chip;
				this.library = library;
				this.moduleNames = moduleNames;
				this.helpers = helpers;
				this.usedModuleNames = usedModuleNames;
				this.output = output;
			}

			public void Write()
			{
				PinDescription[] inputs = chip.InputPins ?? Array.Empty<PinDescription>();
				PinDescription[] outputs = chip.OutputPins ?? Array.Empty<PinDescription>();
				List<string> portList = new();

				// The chip's own pins are addressed by (pin ID, 0) inside the chip.
				foreach (PinDescription pin in inputs)
				{
					Net net = new() { Name = Unique(Identifier(pin.Name), usedNames), Width = (int)pin.BitCount, IsPort = true };
					sources[(pin.ID, 0)] = net;
					portList.Add($"input {Range(net.Width)}{net.Name}");
				}

				foreach (PinDescription pin in outputs)
				{
					Net net = new() { Name = Unique(Identifier(pin.Name), usedNames), Width = (int)pin.BitCount, IsPort = true };
					targets[(pin.ID, 0)] = net;
					portList.Add($"output {Range(net.Width)}{net.Name}");
				}

				foreach (SubChipDescription sub in chip.SubChips ?? Array.Empty<SubChipDescription>())
				{
					ChipDescription description = library.GetChipDescription(sub.Name);
					subChipDescriptions[sub.ID] = description;
					string prefix = "c" + sub.ID.ToString(CultureInfo.InvariantCulture) + "_";

					foreach (PinDescription pin in description.InputPins ?? Array.Empty<PinDescription>())
					{
						targets[(sub.ID, pin.ID)] = Declare(prefix + Identifier(pin.Name), (int)pin.BitCount);
					}

					foreach (PinDescription pin in description.OutputPins ?? Array.Empty<PinDescription>())
					{
						sources[(sub.ID, pin.ID)] = Declare(prefix + Identifier(pin.Name), (int)pin.BitCount);
					}
				}

				WriteConnections();
				foreach (SubChipDescription sub in chip.SubChips ?? Array.Empty<SubChipDescription>()) WriteSubChip(sub, subChipDescriptions[sub.ID]);
				WriteUndrivenTargets();

				output.AppendLine($"// Rewired chip \"{chip.Name}\"");
				output.AppendLine($"module {moduleNames[chip.Name]} (");
				for (int i = 0; i < portList.Count; i++) output.AppendLine("\t" + portList[i] + (i < portList.Count - 1 ? "," : string.Empty));
				output.AppendLine(");");
				output.Append(declarations);
				if (declarations.Length > 0) output.AppendLine();
				output.Append(statements);
				output.AppendLine("endmodule");
				output.AppendLine();
			}

			Net Declare(string baseName, int width)
			{
				Net net = new() { Name = Unique(baseName, usedNames), Width = width };
				declarations.AppendLine($"\twire {Range(width)}{net.Name};");
				return net;
			}

			// Wires store pin-to-pin endpoints (wire-to-wire junctions keep the original
			// source pin), so each distinct pair is one continuous assignment. Several
			// drivers on one target resolve like a tri-state bus.
			void WriteConnections()
			{
				HashSet<(int, int, int, int)> seen = new();
				foreach (WireDescription wire in chip.Wires ?? Array.Empty<WireDescription>())
				{
					PinAddress s = wire.SourcePinAddress;
					PinAddress t = wire.TargetPinAddress;
					if (!seen.Add((s.PinOwnerID, s.PinID, t.PinOwnerID, t.PinID))) continue;

					if (!TryResolve(sources, s, out Net source) || !TryResolve(targets, t, out Net target))
					{
						statements.AppendLine($"\t// skipped a wire to a pin that no longer exists ({s} -> {t})");
						continue;
					}

					statements.AppendLine($"\tassign {target.Name} = {source.Name};");
					target.Driven = true;
				}
			}

			// Mirrors SimChip.GetSimPinFromAddress: subchip pins first, then the chip's own pins.
			bool TryResolve(Dictionary<(int, int), Net> nets, PinAddress address, out Net net)
			{
				if (subChipDescriptions.ContainsKey(address.PinOwnerID) && nets.TryGetValue((address.PinOwnerID, address.PinID), out net)) return true;
				return nets.TryGetValue((address.PinOwnerID, 0), out net);
			}

			void WriteUndrivenTargets()
			{
				foreach (Net net in targets.Values)
				{
					// Rewired reads an unconnected input as low.
					if (!net.Driven) statements.AppendLine($"\tassign {net.Name} = {net.Width}'d0;");
				}
			}

			Net In(int subId, ChipDescription d, int index) => targets[(subId, d.InputPins[index].ID)];
			Net Out(int subId, ChipDescription d, int index) => sources[(subId, d.OutputPins[index].ID)];

			void WriteSubChip(SubChipDescription sub, ChipDescription d)
			{
				int id = sub.ID;
				string label = string.IsNullOrWhiteSpace(sub.Label) ? string.Empty : " // " + sub.Label.Replace('\n', ' ').Replace('\r', ' ');

				switch (d.ChipType)
				{
					case ChipType.Custom:
					{
						List<string> connections = new();
						Dictionary<string, string> childPorts = PortNames(d);
						foreach (PinDescription pin in d.InputPins ?? Array.Empty<PinDescription>()) connections.Add($".{childPorts[PortKey(true, pin.ID)]}({targets[(id, pin.ID)].Name})");
						foreach (PinDescription pin in d.OutputPins ?? Array.Empty<PinDescription>()) connections.Add($".{childPorts[PortKey(false, pin.ID)]}({sources[(id, pin.ID)].Name})");
						statements.AppendLine($"\t{moduleNames[d.Name]} u{id} ({string.Join(", ", connections)});{label}");
						break;
					}
					case ChipType.Nand:
						// Built-in NAND inputs are "IN B" (ID 0) and "IN A" (ID 1).
						statements.AppendLine($"\tassign {Out(id, d, 0).Name} = ~({In(id, d, 1).Name} & {In(id, d, 0).Name});{label}");
						break;
					case ChipType.TriStateBuffer:
						statements.AppendLine($"\tassign {Out(id, d, 0).Name} = {In(id, d, 1).Name} ? {In(id, d, 0).Name} : 1'bz;{label}");
						break;
					case ChipType.Split_4To1Bit:
					case ChipType.Split_8To1Bit:
					{
						// Output 0 is the most significant bit.
						int bits = d.ChipType == ChipType.Split_4To1Bit ? 4 : 8;
						for (int k = 0; k < bits; k++) statements.AppendLine($"\tassign {Out(id, d, k).Name} = {In(id, d, 0).Name}[{bits - 1 - k}];");
						break;
					}
					case ChipType.Split_8To4Bit:
						statements.AppendLine($"\tassign {Out(id, d, 0).Name} = {In(id, d, 0).Name}[7:4];");
						statements.AppendLine($"\tassign {Out(id, d, 1).Name} = {In(id, d, 0).Name}[3:0];");
						break;
					case ChipType.Merge_1To4Bit:
					case ChipType.Merge_1To8Bit:
					case ChipType.Merge_4To8Bit:
					{
						// Input 0 is the most significant part.
						List<string> parts = new();
						for (int k = 0; k < d.InputPins.Length; k++) parts.Add(In(id, d, k).Name);
						statements.AppendLine($"\tassign {Out(id, d, 0).Name} = {{{string.Join(", ", parts)}}};");
						break;
					}
					case ChipType.Bus_1Bit:
					case ChipType.Bus_4Bit:
					case ChipType.Bus_8Bit:
						statements.AppendLine($"\tassign {Out(id, d, 0).Name} = {In(id, d, 0).Name};");
						break;
					case ChipType.BusTerminus_1Bit:
					case ChipType.BusTerminus_4Bit:
					case ChipType.BusTerminus_8Bit:
						break;
					case ChipType.Clock:
						helpers.Add(ClockModule);
						statements.AppendLine($"\t{ClockModule} u{id} (.clk({Out(id, d, 0).Name}));{label}");
						break;
					case ChipType.Key:
						helpers.Add(KeyModule);
						statements.AppendLine($"\t{KeyModule} u{id} (.out({Out(id, d, 0).Name})); // key '{KeyName(sub)}': drive from a testbench");
						break;
					case ChipType.Pulse:
					{
						helpers.Add(PulseModule);
						uint width = sub.InternalData != null && sub.InternalData.Length > 0 ? sub.InternalData[0] : 1;
						statements.AppendLine($"\t{PulseModule} #(.WIDTH({width})) u{id} (.in({In(id, d, 0).Name}), .pulse({Out(id, d, 0).Name}));{label}");
						break;
					}
					case ChipType.Rom_256x16:
						WriteRom(sub, d);
						break;
					default:
						statements.AppendLine($"\t// {d.Name} (u{id}) has no hardware equivalent and is not exported{label}");
						for (int k = 0; k < (d.OutputPins?.Length ?? 0); k++) statements.AppendLine($"\tassign {Out(id, d, k).Name} = {Out(id, d, k).Width}'d0;");
						break;
				}
			}

			void WriteRom(SubChipDescription sub, ChipDescription d)
			{
				int id = sub.ID;
				string memory = Unique($"c{id}_rom", usedNames);
				declarations.AppendLine($"\treg [15:0] {memory} [0:255];");

				StringBuilder init = new();
				init.AppendLine("\tinitial begin");
				uint[] data = sub.InternalData ?? Array.Empty<uint>();
				for (int i = 0; i < 256; i++)
				{
					uint word = i < data.Length ? data[i] & 0xFFFF : 0;
					init.AppendLine($"\t\t{memory}[{i}] = 16'h{word:X4};");
				}

				init.AppendLine("\tend");
				statements.Append(init);

				// Output 0 ("OUT B") is the high byte, output 1 ("OUT A") the low byte.
				string address = In(id, d, 0).Name;
				statements.AppendLine($"\tassign {Out(id, d, 0).Name} = {memory}[{address}][15:8];");
				statements.AppendLine($"\tassign {Out(id, d, 1).Name} = {memory}[{address}][7:0];");
			}

			static string KeyName(SubChipDescription sub)
			{
				if (sub.InternalData == null || sub.InternalData.Length == 0) return "?";
				uint code = sub.InternalData[0];
				return code is >= 32 and < 127 ? ((char)code).ToString() : code.ToString(CultureInfo.InvariantCulture);
			}
		}

		// Port names of the module exported for this chip, in pin order.
		public static string[] InputPortNames(ChipDescription d) => Array.ConvertAll(d.InputPins ?? Array.Empty<PinDescription>(), p => PortNames(d)[PortKey(true, p.ID)]);
		public static string[] OutputPortNames(ChipDescription d) => Array.ConvertAll(d.OutputPins ?? Array.Empty<PinDescription>(), p => PortNames(d)[PortKey(false, p.ID)]);

		// Port names exactly as the child's own module declares them.
		static Dictionary<string, string> PortNames(ChipDescription d)
		{
			Dictionary<string, string> names = new(StringComparer.Ordinal);
			HashSet<string> used = new(StringComparer.Ordinal);
			foreach (PinDescription pin in d.InputPins ?? Array.Empty<PinDescription>()) names[PortKey(true, pin.ID)] = Unique(Identifier(pin.Name), used);
			foreach (PinDescription pin in d.OutputPins ?? Array.Empty<PinDescription>()) names[PortKey(false, pin.ID)] = Unique(Identifier(pin.Name), used);
			return names;
		}

		static string PortKey(bool input, int id) => (input ? "i" : "o") + id.ToString(CultureInfo.InvariantCulture);

		static string Range(int width) => width > 1 ? $"[{width - 1}:0] " : string.Empty;

		public static string Identifier(string name)
		{
			StringBuilder sb = new();
			foreach (char c in name ?? string.Empty)
			{
				if (c is >= 'a' and <= 'z' or >= 'A' and <= 'Z' or >= '0' and <= '9' or '_') sb.Append(c);
				else if (sb.Length > 0 && sb[^1] != '_') sb.Append('_');
			}

			string id = sb.ToString().Trim('_');
			if (id.Length == 0) id = "unnamed";
			if (char.IsDigit(id[0])) id = "n" + id;
			if (Keywords.Contains(id)) id += "_";
			return id;
		}

		static string Unique(string name, HashSet<string> used)
		{
			string candidate = name;
			for (int i = 2; !used.Add(candidate); i++) candidate = name + "_" + i.ToString(CultureInfo.InvariantCulture);
			return candidate;
		}

		const string ClockModuleSource = @"// Simulation-only clock (Rewired advances its clock in simulation ticks).
module rewired_clock (output reg clk);
	initial clk = 1'b0;
	always #5 clk = ~clk;
endmodule

";

		const string KeyModuleSource = @"// Simulation-only key input; force it from a testbench.
module rewired_key (output out);
	assign out = 1'b0;
endmodule

";

		const string PulseModuleSource = @"// Simulation-only pulse: goes high for WIDTH clock periods after a rising input.
module rewired_pulse #(parameter WIDTH = 1) (input in, output reg pulse);
	initial pulse = 1'b0;
	always @(posedge in) begin
		pulse = 1'b1;
		#(10 * WIDTH) pulse = 1'b0;
	end
endmodule

";
	}
